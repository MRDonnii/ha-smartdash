#!/bin/sh
set -eu

# First-run setup for a dedicated HA Smartdash nginx virtual host. Values may
# be supplied as SMARTDASH_* environment variables for Docker/Unraid.
say() { printf '%s\n' "$*"; }
fail() { say "FEJL: $*" >&2; exit 1; }

prompt() {
  prompt_name=$1; prompt_text=$2; prompt_default=$3
  eval "prompt_value=\${$prompt_name:-}"
  if [ -z "$prompt_value" ]; then
    if [ ! -t 0 ]; then prompt_value=$prompt_default
    else
      printf '%s [%s]: ' "$prompt_text" "$prompt_default"
      IFS= read -r prompt_value
      prompt_value=${prompt_value:-$prompt_default}
    fi
    case "$prompt_name" in
      SMARTDASH_HA_URL) SMARTDASH_HA_URL=$prompt_value ;;
      SMARTDASH_WEB_ROOT) SMARTDASH_WEB_ROOT=$prompt_value ;;
      SMARTDASH_NGINX_CONF) SMARTDASH_NGINX_CONF=$prompt_value ;;
      SMARTDASH_LISTEN_PORT) SMARTDASH_LISTEN_PORT=$prompt_value ;;
      SMARTDASH_SERVER_NAME) SMARTDASH_SERVER_NAME=$prompt_value ;;
      SMARTDASH_PHP_UPSTREAM) SMARTDASH_PHP_UPSTREAM=$prompt_value ;;
      *) fail "Ukendt opsætningsfelt: $prompt_name" ;;
    esac
  fi
}

# Looks for Home Assistant on the local network and prints one "url name" line
# per installation: mDNS first, then a short port 8123 scan of the /24 networks
# this machine is on. A Home Assistant answers GET /api/ with 401 Unauthorized.
discover_ha() {
  found_file=$(mktemp)
  scan_file=$(mktemp)
  if command -v avahi-browse >/dev/null 2>&1; then
    avahi-browse -rpt _home-assistant._tcp 2>/dev/null | awk -F';' '$1 == "=" && $3 == "IPv4" { gsub(/\\032/, " ", $4); print "http://" $8 ":" $9 " " $4 }' >>"$found_file" || true
  fi
  if command -v curl >/dev/null 2>&1; then
    prefixes=$(
      { ip -4 -o addr show scope global 2>/dev/null | awk '{ sub(/\/.*/, "", $4); print $4 }'
        hostname -I 2>/dev/null | tr ' ' '\n'; } |
        awk -F. 'NF == 4 && ($1 == 10 || ($1 == 192 && $2 == 168) || ($1 == 172 && $2 >= 16 && $2 <= 31)) { print $1 "." $2 "." $3 }' | sort -u | head -3
    )
    for prefix in $prefixes; do
      host_number=1
      while [ "$host_number" -le 254 ]; do
        (
          target="$prefix.$host_number"
          reply=$(curl -s -m 1 "http://$target:8123/api/" 2>/dev/null || true)
          case "$reply" in *"401: Unauthorized"*) printf 'http://%s:8123 Home Assistant\n' "$target" >>"$scan_file" ;; esac
        ) &
        host_number=$((host_number + 1))
        [ $((host_number % 64)) -eq 0 ] && wait
      done
      wait
    done
  fi
  cat "$found_file" "$scan_file" | awk '!seen[$1]++'
  rm -f "$found_file" "$scan_file"
}

choose_ha_url() {
  say "Søger efter Home Assistant på netværket..."
  discovered=$(discover_ha)
  if [ -z "$discovered" ]; then
    say "Jeg fandt ingen Home Assistant automatisk."
    return 0
  fi
  say "Fundet:"
  choice_number=0
  OLD_IFS=$IFS
  IFS='
'
  for line in $discovered; do
    choice_number=$((choice_number + 1))
    say "  $choice_number) ${line%% *}  (${line#* })"
  done
  IFS=$OLD_IFS
  printf 'Vælg nummer [1], eller skriv 0 for at indtaste adressen selv: '
  IFS= read -r choice_value
  case "$choice_value" in
    '') choice_value=1 ;;
    http://*|https://*) SMARTDASH_HA_URL=$choice_value; return 0 ;;
    *[!0-9]*) return 0 ;;
  esac
  if [ "$choice_value" -ge 1 ] && [ "$choice_value" -le "$choice_number" ]; then
    picked=$(printf '%s\n' "$discovered" | sed -n "${choice_value}p")
    SMARTDASH_HA_URL=${picked%% *}
  fi
}

if [ -z "${SMARTDASH_HA_URL:-}" ] && [ -t 0 ]; then choose_ha_url; fi
prompt SMARTDASH_HA_URL "Home Assistant intern URL" "http://homeassistant.local:8123"
prompt SMARTDASH_WEB_ROOT "Smartdash webrod" "/var/www/ha-smartdash"
prompt SMARTDASH_NGINX_CONF "Aktiv Nginx serverfil" "/etc/nginx/conf.d/ha-smartdash.conf"
prompt SMARTDASH_LISTEN_PORT "Smartdash HTTP-port" "80"
prompt SMARTDASH_SERVER_NAME "Nginx server_name" "_"
prompt SMARTDASH_PHP_UPSTREAM "PHP-FPM upstream" "unix:/run/php/php-fpm.sock"

case "$SMARTDASH_HA_URL" in http://*|https://*) ;; *) fail "HA URL skal begynde med http:// eller https://" ;; esac
case "$SMARTDASH_LISTEN_PORT" in ''|*[!0-9]*) fail "HTTP-porten skal være et tal" ;; esac
for config_value in "$SMARTDASH_HA_URL" "$SMARTDASH_WEB_ROOT" "$SMARTDASH_NGINX_CONF" "$SMARTDASH_SERVER_NAME" "$SMARTDASH_PHP_UPSTREAM"; do
  case "$config_value" in *';'*|*'{'*|*'}'*) fail "Opsætningsværdier må ikke indeholde semikolon eller krøllede parenteser" ;; esac
done
HA_UPSTREAM=${SMARTDASH_HA_URL%/}
CONF_DIR=$(dirname "$SMARTDASH_NGINX_CONF")
[ -d "$CONF_DIR" ] || mkdir -p "$CONF_DIR"
TMP_CONF="${SMARTDASH_NGINX_CONF}.new.$$"
trap 'rm -f "$TMP_CONF"' EXIT HUP INT TERM

cat > "$TMP_CONF" <<EOF
# Generated by HA Smartdash deploy/setup-smartdash.sh
server {
    listen ${SMARTDASH_LISTEN_PORT};
    server_name ${SMARTDASH_SERVER_NAME};
    root ${SMARTDASH_WEB_ROOT};
    index index.html;
    location / { try_files \$uri \$uri/ /index.html; }
    location ~ \.php\$ {
        include fastcgi_params;
        fastcgi_param SCRIPT_FILENAME \$document_root\$fastcgi_script_name;
        fastcgi_pass ${SMARTDASH_PHP_UPSTREAM};
    }
    location = /ha { return 301 /ha/; }
    location /ha/ {
        proxy_pass ${HA_UPSTREAM}/;
        proxy_http_version 1.1;
        proxy_set_header Host \$proxy_host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_buffering off;
        proxy_read_timeout 3600s;
    }
    location ~ ^/(data|\.git)/ { deny all; return 404; }
}
EOF

BACKUP=
if [ -f "$SMARTDASH_NGINX_CONF" ]; then
  BACKUP="${SMARTDASH_NGINX_CONF}.bak.$(date +%Y%m%d-%H%M%S)"
  cp "$SMARTDASH_NGINX_CONF" "$BACKUP"
  say "Backup gemt: $BACKUP"
fi
mv "$TMP_CONF" "$SMARTDASH_NGINX_CONF"
trap - EXIT HUP INT TERM
say "Nginx-konfiguration skrevet: $SMARTDASH_NGINX_CONF"

if command -v nginx >/dev/null 2>&1; then
  if ! nginx -t; then
    if [ -n "$BACKUP" ]; then
      cp "$BACKUP" "$SMARTDASH_NGINX_CONF"
      say "Den tidligere Nginx-konfiguration er automatisk gendannet."
    else
      mv "$SMARTDASH_NGINX_CONF" "${SMARTDASH_NGINX_CONF}.invalid"
      say "Den ugyldige fil er flyttet til ${SMARTDASH_NGINX_CONF}.invalid."
    fi
    fail "nginx -t fejlede; den nye konfiguration blev ikke aktiveret"
  fi
  if [ "${SMARTDASH_RELOAD_NGINX:-1}" = "1" ]; then nginx -s reload; say "Nginx er genindlæst."; fi
else
  say "Nginx findes ikke her; valider/genindlæs den aktive container efterfølgende."
fi

SMARTDASH_PUBLIC_URL=${SMARTDASH_PUBLIC_URL:-"http://127.0.0.1:${SMARTDASH_LISTEN_PORT}"}
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
if command -v curl >/dev/null 2>&1; then
  say "Tester Home Assistant-loginproxy..."
  sh "$SCRIPT_DIR/check-install.sh" "$SMARTDASH_PUBLIC_URL" || {
    say "HTTP 400 betyder normalt, at HA mangler Nginx-IP'en under http.trusted_proxies."
    exit 1
  }
else say "curl findes ikke; proxytesten blev sprunget over."
fi
say "Opsætningen er færdig. Åbn ${SMARTDASH_PUBLIC_URL%/}/admin/"
